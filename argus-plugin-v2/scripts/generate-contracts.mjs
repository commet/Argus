#!/usr/bin/env node
// Single-source GENERATOR (dim2: drift detection → drift prevention).
//
// Argus has two bodies — webapp (TS) and plugin (markdown) — with no shared runtime.
// JS consumers can import a JSON contract directly (no drift possible). But a markdown
// skill can't import — so its copy must be GENERATED from the source and checked in
// CI, or it silently drifts. This script is that generator; today it emits the
// machinery-terms reference fragment, and is the place to add each cross-surface
// contract (crisis taxonomy, course-status, request-types) as the active sessions
// that own those files free up.
//
//   node scripts/generate-contracts.mjs          # (re)write generated artifacts
//   node scripts/generate-contracts.mjs --check   # CI: fail if any artifact is stale

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pluginRoot = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');

const AUTO = '<!-- AUTO-GENERATED by scripts/generate-contracts.mjs from data/contracts/ — do not edit by hand -->';

// Each entry: { source JSON, output path, render(data) -> string }
const ARTIFACTS = [
  {
    source: 'data/contracts/machinery-terms.json',
    output: 'skills/_generated/forbidden-terms.md',
    render: (d) =>
      `${AUTO}\n\n# Forbidden machinery terms (reference)\n\nA user-facing Current Heading must never leak these (the product is orientation, not a workflow report):\n\n${d.forbidden_surface_terms.map((t) => `- \`${t}\``).join('\n')}\n`,
  },
  {
    source: 'data/contracts/crisis-taxonomy.json',
    output: 'skills/_generated/crisis-taxonomy.md',
    render: (d) =>
      `${AUTO}\n\n# Crisis taxonomy (Axis-0 reference)\n\nclarify Step 1.6 screens for these BEFORE request-type. On a hit: off-ramp to a human resource, no decision verdict.\n\n${d.categories.map((c) => `- **${c.id}** — ${c.desc}`).join('\n')}\n`,
  },
  {
    source: 'data/contracts/course-status.json',
    output: 'skills/_generated/course-status.md',
    render: (d) =>
      `${AUTO}\n\n# Course-status legend (current_course.status)\n\nThe practical course a bearing reports. Same set in the webapp + the bearing schema.\n\n${d.statuses.map((s) => `- **${s.id}** — ${s.desc}`).join('\n')}\n`,
  },
];

// Parity assertions: a contract whose authoritative copy lives in webapp TS (can't
// import the plugin JSON) — verify the TS const matches the source instead of
// rewriting it. Same generate-then-check discipline, applied across the surface seam.
const PARITY = [
  {
    source: 'data/contracts/crisis-taxonomy.json',
    tsFile: '../src/lib/crisis-gate.ts',
    extract: (ts) => {
      const m = ts.match(/export const CRISIS_CATEGORIES\s*=\s*\[([\s\S]*?)\]\s*as const/);
      if (!m) return null;
      return [...m[1].matchAll(/['"]([a-z_]+)['"]/g)].map((x) => x[1]);
    },
    expected: (d) => d.categories.map((c) => c.id),
    label: 'webapp crisis-gate CRISIS_CATEGORIES ↔ crisis-taxonomy.json',
  },
  {
    source: 'data/contracts/course-status.json',
    tsFile: '../src/lib/current-bearing.ts',
    extract: (ts) => {
      const m = ts.match(/export const COURSE_STATUSES\s*=\s*\[([\s\S]*?)\]\s*as const/);
      if (!m) return null;
      return [...m[1].matchAll(/['"]([a-z_]+)['"]/g)].map((x) => x[1]);
    },
    expected: (d) => d.statuses.map((s) => s.id),
    label: 'webapp current-bearing COURSE_STATUSES ↔ course-status.json',
  },
  {
    source: 'data/contracts/course-status.json',
    tsFile: 'data/schemas/current-bearing.json',
    extract: (text) => {
      try { return JSON.parse(text).properties.current_course.properties.status.enum; }
      catch { return null; }
    },
    expected: (d) => d.statuses.map((s) => s.id),
    label: 'plugin bearing-schema status.enum ↔ course-status.json',
  },
];

let stale = 0;
for (const a of ARTIFACTS) {
  const data = JSON.parse(fs.readFileSync(path.join(pluginRoot, a.source), 'utf8'));
  const expected = a.render(data);
  const outPath = path.join(pluginRoot, a.output);
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null;
  if (check) {
    if (current !== expected) {
      stale++;
      console.error(`STALE: ${a.output} is out of sync with ${a.source} — run: node scripts/generate-contracts.mjs`);
    }
  } else {
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, expected);
    console.log(`generated ${a.output} from ${a.source}`);
  }
}

// Parity assertions run in BOTH modes (a drift here is always a failure).
for (const p of PARITY) {
  const data = JSON.parse(fs.readFileSync(path.join(pluginRoot, p.source), 'utf8'));
  const tsPath = path.join(pluginRoot, p.tsFile);
  const got = fs.existsSync(tsPath) ? p.extract(fs.readFileSync(tsPath, 'utf8')) : null;
  const want = p.expected(data);
  const equal = got && got.length === want.length && want.every((w, i) => got[i] === w);
  if (!equal) {
    stale++;
    console.error(`DRIFT: ${p.label}\n  source: ${JSON.stringify(want)}\n  TS:     ${JSON.stringify(got)}`);
  }
}

if (stale) process.exit(1);
if (check) console.log(`generate-contracts: ${ARTIFACTS.length} artifact(s) in sync, ${PARITY.length} parity assertion(s) ok.`);
