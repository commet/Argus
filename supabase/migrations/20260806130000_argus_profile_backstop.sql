-- TWIN — 프로필 추출의 백스톱 표식 (2026-08-06 밤).
--
-- 왜 컬럼이 하나 더 필요한가:
--
-- 프로필 추출은 정산 응답 뒤(`after()`)에서 돈다. 서버리스에서 그 경로는
-- 실패할 수 있고(람다가 얼면 떠 있는 promise 는 죽는다), 그림자와 달리
-- **프로필에는 백스톱이 없었다.** 즉 "정산했는데 분신이 아무것도 배우지 않는"
-- 조용한 실패가 가능했다 — 화면에는 아무 표시도 나지 않는 종류의 실패다.
--
-- 백스톱을 만들려면 "이 케이스에 추출을 **시도했는가**"를 알아야 한다.
-- "프로필 항목이 이 케이스를 근거로 갖는가"로는 안 된다: 추출이 정상적으로
-- 돌고도 아무것도 만들지 않는 것이 흔한 정상 결과이기 때문이다(없음이 정직한
-- 답일 수 있다). 그 경우를 미시도로 오인하면 크론이 같은 케이스에 대해
-- 48시간 동안 매시간 LLM 을 부른다.
--
-- 그래서 시도 시각을 케이스에 남긴다. **성공/실패가 아니라 시도**다 —
-- LLM 호출 자체가 실패했을 때는 남기지 않아 크론이 다시 집는다.

alter table public.argus_cases
  add column if not exists profile_extracted_at timestamptz;

comment on column public.argus_cases.profile_extracted_at is
  'TWIN — 판단 프로필 추출을 시도한 시각. null 이면 크론 백스톱이 집어간다. 항목이 0건이어도 시도했으면 채워진다.';
