/**
 * 전제인가, 아직 답 안 한 질문인가 (2026-07-29 신설).
 *
 * ── 왜 필요한가 ─────────────────────────────────────────────────────────
 * 자료 구조는 처음부터 둘을 구분해 왔다:
 *   · `premise`       — 나중에 **현실과 맞춰볼 수 있는** 문장
 *   · `open_question` — 사용자가 **아직 답하지 않은 물음** (현실이 답해주지 않는다)
 *
 * 그런데 만드는 쪽이 그 구분을 안 썼다. 웹의 자동 추적은 나오는 문장을 전부
 * `type: 'premise'` 로 못 박고, 그 텍스트는 LLM 이 쓴 `key_assumptions` 에서 온다.
 * 프롬프트에는 "이 문서가 기대는 가정 4개까지"라고만 적혀 있어 모양 제약이 없다.
 * 그래서 물음표로 끝나는 문장이 "확인할 전제"로 저장된다.
 *
 * 그게 왜 나쁜가: 확인일에 "이 전제가 맞았나요?"라고 물었는데 그 자리에
 * "이 일정이 현실적으로 가능한가요?"가 들어 있으면 **답할 수가 없다.** 물음은
 * 참/거짓이 없다. 이름표와 내용이 다르면 사용자는 화면 전체를 못 믿게 된다.
 *
 * ── 고치는 방향 ─────────────────────────────────────────────────────────
 * **버리지 않는다.** 물음은 쓸모없는 게 아니라 자리가 틀렸을 뿐이고, 그 자리는
 * 이미 있다(`open_question`). 그래서 지우는 대신 **옮긴다.**
 *
 * ── 판정은 보수적으로 ───────────────────────────────────────────────────
 * 틀린 방향의 비용이 다르다. 진짜 전제를 질문으로 잘못 보내면 현실 대조 대상이
 * 하나 사라진다(손해). 물음을 전제로 두면 답할 수 없는 걸 묻게 된다(더 큰 손해).
 * 그래도 **확신할 때만** 질문으로 옮긴다 — 애매하면 전제로 둔다. 서술문 안에
 * 우연히 들어간 "~인지"류에 걸려 멀쩡한 전제가 사라지는 쪽이 더 조용한 고장이다.
 */

/** 문장 끝의 물음표 (전각 포함). 가장 확실한 신호다. */
const TRAILING_QUESTION_MARK = /[?？]\s*$/;

/**
 * 물음표 없이도 물음인 한국어 종결 어미. **종결 위치에서만** 본다 —
 * "가능한지 확인하세요"의 '~는지'는 문장 중간이고 그건 서술문이다.
 *
 * 조합형 음절만 쓴다 (2026-07-30): 낱자모 대안(`ㄹ까`, `ㅂ니까`)은 조합형
 * 한글 텍스트에 낱자모가 없어 **애초에 맞을 수 없는 죽은 규칙**이었다 —
 * "이게 사실입니까"가 전제로 저장되고 있었다. `~(으)니까`(이유)는 넣지
 * 않는다 — "예산이 없으니까."는 물음이 아니다 (보수 판정 원칙).
 */
const KO_INTERROGATIVE_ENDING = /(나요|까요|을까|할까|될까|볼까|갈까|인가|는가|은가|습니까|입니까|합니까|됩니까|일까|던가)[.!\s]*$/;

/** 서술문인데 우연히 물음표가 붙은 경우를 되살릴 여지 — 지금은 두지 않는다. */

export type PremiseShape = 'premise' | 'open_question';

/**
 * 이 문장이 물음인가. 확신할 때만 true.
 *
 * 여러 문장이 붙어 있으면 **마지막 문장**으로 판정한다 — LLM 이 흔히 쓰는
 * "…촉박합니다. 이게 현실적으로 가능한가요?" 같은 꼴에서 물음이 끝에 온다.
 */
export function isQuestionShaped(text: string | null | undefined): boolean {
  const t = (text ?? '').trim();
  if (!t) return false;
  if (TRAILING_QUESTION_MARK.test(t)) return true;
  // 마지막 문장만 따로 본다. 앞에 서술이 길어도 끝이 물음이면 물음이다.
  const lastSentence = t.split(/(?<=[.!?？。])\s+/).pop()?.trim() ?? t;
  return KO_INTERROGATIVE_ENDING.test(lastSentence);
}

/** 이 문장이 앉을 자리. 만드는 쪽은 전부 이 함수를 거친다. */
export function premiseShapeOf(text: string | null | undefined): PremiseShape {
  return isQuestionShaped(text) ? 'open_question' : 'premise';
}

/**
 * 두 문장이 사실상 같은 주장인가 (2026-07-30 — judgment-card 에서 승격).
 *
 * 왜 여기로 왔나: 실주행 카드에 "다음 분기 매출이 지금 수준을 유지한다"와
 * "다음 분기 매출은 확정 계약 기준으로 현재와 유사한 수준을 유지한다"가 **두 줄로**
 * 찍혔다. 같은 생각 하나다. 이 판정이 카드 안에만 있으면 추적 저장소도 같은 병에
 * 걸린다 — 같은 전제가 두 항목으로 저장되면 사용자는 같은 걸 두 번 확인하고,
 * 전제 감시는 같은 웹 조사를 두 번 한다(비용). 문장 모양의 판정은 전부 이 파일 —
 * 그래야 카드와 저장소가 다른 답을 내는 날이 안 온다.
 *
 * 한국어 함정: 교착어라 같은 낱말이 자리마다 다른 꼬리를 단다. "매출이"와
 * "매출은"을 다른 낱말로 세면 같은 문장의 겹침이 0.67에서 멈춰 통과한다(실측).
 * 그래서 조사를 떼고 센다. 과잉 절단 방지: 떼고 한 글자만 남으면 원형을 쓴다.
 *
 * 판정은 보수적으로 — 겹침이 확실할 때(작은 쪽 기준 70%)만 같은 주장으로 본다.
 * 서로 다른 전제를 잘못 합치면 현실 대조 대상이 조용히 사라진다. 그쪽이 더
 * 알아채기 어려운 고장이다.
 */
export function sameClaim(a: string, b: string): boolean {
  const PARTICLE = /(으로|에서|부터|까지|이|가|은|는|을|를|의|에|로|와|과|도|만)$/;
  const stem = (w: string) => {
    const s = w.replace(PARTICLE, '');
    return s.length >= 2 ? s : w;
  };
  const tokens = (s: string) => new Set(
    s.toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, ' ').split(/\s+/)
      .filter((w) => w.length >= 2).map(stem),
  );
  const ta = tokens(a);
  const tb = tokens(b);
  if (ta.size === 0 || tb.size === 0) return false;
  let shared = 0;
  for (const w of ta) if (tb.has(w)) shared++;
  // 작은 쪽 기준 — 한쪽이 길게 부연했을 뿐인 경우를 잡아야 한다.
  return shared / Math.min(ta.size, tb.size) >= 0.7;
}
